#!/usr/bin/env node
// Generates src/db/schema.generated.ts from src/db/schema.sql so the schema can
// be imported as a plain string in both the Worker build and the test runner.
// Run via `pnpm --filter worker codegen` (also invoked before typecheck/test).
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const sqlPath = fileURLToPath(new URL("../src/db/schema.sql", import.meta.url));
const outPath = fileURLToPath(
  new URL("../src/db/schema.generated.ts", import.meta.url),
);
const sql = readFileSync(sqlPath, "utf8");

const banner = `// AUTO-GENERATED by scripts/gen-schema.mjs from src/db/schema.sql — do not edit.
export const SCHEMA_SQL = ${JSON.stringify(sql)};
`;

writeFileSync(outPath, banner);
console.log("schema.generated.ts written");
